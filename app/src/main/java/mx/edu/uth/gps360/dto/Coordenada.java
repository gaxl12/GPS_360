package mx.edu.uth.gps360.dto;

public class Coordenada {
    private String latitud;
    private String longitud;
    private String fecha_reguistro;

    public String getLatitud() { return latitud; }
    public void setLatitud(String latitud) { this.latitud = latitud; }
    public String getLongitud() { return longitud; }
    public void setLongitud(String longitud) { this.longitud = longitud; }
    public String getFechaReguistro() { return fecha_reguistro; }
    public void setFechaReguistro(String fecha_reguistro) { this.fecha_reguistro = fecha_reguistro; }
}
